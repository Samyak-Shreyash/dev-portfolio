import jwt from 'jsonwebtoken';
import { cookies } from 'next/headers';
import { createHash, createHmac, randomUUID, timingSafeEqual } from 'crypto';

export const SESSION_COOKIE = 'admin_session';
export const SESSION_MAX_AGE = 60 * 60 * 8; // 8 hours

const CHALLENGE_AUDIENCE = 'admin-login-challenge';
const CHALLENGE_MAX_AGE = 60 * 2; // 2 minutes

// No fallback secret: a guessable default would let anyone forge an admin session
function getSecret() {
  const secret = process.env.JWT_SECRET;
  if (!secret || secret.length < 32) {
    throw new Error('JWT_SECRET must be set to at least 32 characters');
  }
  return secret;
}

// Single admin user: the session only needs to prove it was issued by us
export function signSession() {
  return jwt.sign({ sub: 'admin' }, getSecret(), { algorithm: 'HS256', expiresIn: SESSION_MAX_AGE });
}

export async function isAdmin() {
  const token = (await cookies()).get(SESSION_COOKIE)?.value;
  if (!token) return false;

  try {
    return (jwt.verify(token, getSecret(), { algorithms: ['HS256'] }) as jwt.JwtPayload).sub === 'admin';
  } catch {
    return false;
  }
}

// Format: iterations.salt.storedKey, generated by scripts/create-login-verifier.mjs
function getLoginVerifier() {
  const [iterations, salt, storedKey] = (process.env.ADMIN_LOGIN_VERIFIER ?? '').split('.');
  if (!Number(iterations) || !salt || !storedKey) {
    throw new Error('ADMIN_LOGIN_VERIFIER is not set or is malformed');
  }
  return { iterations: Number(iterations), salt, storedKey: Buffer.from(storedKey, 'base64') };
}

export function createLoginChallenge() {
  const { iterations, salt } = getLoginVerifier();
  const challenge = jwt.sign({}, getSecret(), {
    algorithm: 'HS256',
    audience: CHALLENGE_AUDIENCE,
    expiresIn: CHALLENGE_MAX_AGE,
    jwtid: randomUUID(),
  });
  return { challenge, iterations, salt };
}

// SCRAM-style check: the proof is ClientKey XOR HMAC(StoredKey, challenge), so the password never leaves the browser
export function verifyLoginProof(challenge: string, proof: string) {
  let payload: jwt.JwtPayload;
  try {
    payload = jwt.verify(challenge, getSecret(), { algorithms: ['HS256'], audience: CHALLENGE_AUDIENCE }) as jwt.JwtPayload;
  } catch {
    return null;
  }
  if (!payload.jti || !payload.exp) return null;

  const { storedKey } = getLoginVerifier();
  const proofBytes = Buffer.from(proof, 'base64');
  if (proofBytes.length !== storedKey.length) return null;

  const signature = createHmac('sha256', storedKey).update(challenge).digest();
  const clientKey = proofBytes.map((byte, i) => byte ^ signature[i]);
  const candidate = createHash('sha256').update(clientKey).digest();
  if (candidate.length !== storedKey.length || !timingSafeEqual(candidate, storedKey)) return null;

  return { nonce: payload.jti, expiresAt: new Date(payload.exp * 1000) };
}

// Salted hash of the client IP, so rate limits work without storing raw IPs
export function hashIp(req: Request) {
  const ip = req.headers.get('x-forwarded-for')?.split(',')[0].trim() || 'unknown';
  return createHash('sha256').update(ip + (process.env.MONGODB_URI ?? '')).digest('hex');
}
